import { pluralLessons } from '@/domain/textFormaters';

describe('pluralLessons', () => {
    it.each([
        [0, '0 уроков'],
        [1, '1 урок'],
        [2, '2 урока'],
        [3, '3 урока'],
        [4, '4 урока'],
        [5, '5 уроков'],
        [6, '6 уроков'],
        [10, '10 уроков'],
        [11, '11 уроков'],
        [12, '12 уроков'],
        [13, '13 уроков'],
        [14, '14 уроков'],
        [15, '15 уроков'],
        [21, '21 урок'],
        [22, '22 урока'],
        [24, '24 урока'],
        [25, '25 уроков'],
        [100, '100 уроков'],
        [101, '101 урок'],
        [102, '102 урока'],
        [104, '104 урока'],
        [111, '111 уроков'],
        [112, '112 уроков'],
        [114, '114 уроков'],
        [121, '121 урок'],
        [122, '122 урока'],
    ])('%i → «%s»', (n, expected) => {
        expect(pluralLessons(n)).toBe(expected);
    });

    it('число всегда попадает в строку', () => {
        expect(pluralLessons(7)).toContain('7');
    });
});
